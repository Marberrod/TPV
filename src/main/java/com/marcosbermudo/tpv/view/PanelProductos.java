    private static class Cuadricula implements java.awt.LayoutManager {
        private static final int LADO = 180;
        private static final int GAP = 10;

        private int ancho(java.awt.Container p) {
            java.awt.Container viewport = javax.swing.SwingUtilities.getAncestorOfClass(javax.swing.JViewport.class, p);
            return viewport != null && viewport.getWidth() > 0 ? viewport.getWidth() : Math.max(p.getWidth(), LADO + 2 * GAP);
        }
        private int columnas(java.awt.Container p) { return Math.max(1, (ancho(p) - GAP) / (LADO + GAP)); }
        private int lado(java.awt.Container p) { return Math.max(1, Math.min(LADO, ancho(p) - 2 * GAP)); }
        public void addLayoutComponent(String name, java.awt.Component c) { }
        public void removeLayoutComponent(java.awt.Component c) { }
        public java.awt.Dimension preferredLayoutSize(java.awt.Container p) {
            int cols = columnas(p);
            int filas = (p.getComponentCount() + cols - 1) / cols;
            return new java.awt.Dimension(ancho(p), GAP + filas * (lado(p) + GAP));
        }
        public java.awt.Dimension minimumLayoutSize(java.awt.Container p) { return new java.awt.Dimension(0, 0); }
        public void layoutContainer(java.awt.Container p) {
            int cols = columnas(p), lado = lado(p);
            for (int i = 0; i < p.getComponentCount(); i++) {
                p.getComponent(i).setBounds(GAP + (i % cols) * (lado + GAP), GAP + (i / cols) * (lado + GAP), lado, lado);
            }
        }
    }

